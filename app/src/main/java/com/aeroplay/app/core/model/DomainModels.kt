data class RemotePlaylistUiState(
    val playlist: PlaylistItem,
    val isLoading: Boolean = true,
    val videos: List<VideoItem> = emptyList(),
    val error: String? = null,
    val hasMore: Boolean = false
)

data class PlaybackQueue(
    val items: List<VideoItem> = emptyList(),
    val currentIndex: Int = -1,
    val queueTitle: String = "Danh sách phát",
    val radioMode: Boolean = false,
    val autoRadioAfterEnd: Boolean = false
) {
    val currentItem: VideoItem?
        get() = items.getOrNull(currentIndex)
    val hasNext: Boolean
        get() = currentIndex in 0 until (items.size - 1)
    val hasPrevious: Boolean
        get() = currentIndex > 0
}

data class PlaybackPosition(
    val videoId: String,
    val positionMs: Long,
    val durationMs: Long,
    val updatedAtEpochMs: Long = System.currentTimeMillis()
) {
    val progressFraction: Float
        get() = if (durationMs > 0L) (positionMs.toFloat() / durationMs.toFloat()).coerceIn(0f, 1f) else 0f
}

sealed class SourceError(open val message: String, open val technicalDetail: String? = null) {
    data class NetworkError(
        override val message: String = "Không thể kết nối mạng. Vui lòng kiểm tra Wi-Fi hoặc dữ liệu di động.",
        override val technicalDetail: String? = null
    ) : SourceError(message, technicalDetail)

    data class NoStreamAvailable(
        override val message: String = "Video này không có luồng phát (stream) tương thích khả dụng.",
        override val technicalDetail: String? = null
    ) : SourceError(message, technicalDetail)

    data class AgeRestricted(
        override val message: String = "Nội dung giới hạn độ tuổi. AeroPlay không vượt rào xác thực hoặc lấy cookie tài khoản.",
        override val technicalDetail: String? = null
    ) : SourceError(message, technicalDetail)

    data class GeoRestricted(
        override val message: String = "Nội dung bị giới hạn khu vực địa lý bởi nhà cung cấp.",
        override val technicalDetail: String? = null
    ) : SourceError(message, technicalDetail)

    data class PrivateOrPaidContent(
        override val message: String = "Nội dung riêng tư, hội viên hoặc yêu cầu trả phí / DRM.",
        override val technicalDetail: String? = null
    ) : SourceError(message, technicalDetail)

    data class RateLimitedOrCaptcha(
        override val message: String = "Nguồn nội dung yêu cầu xác thực CAPTCHA hoặc giới hạn tần suất truy cập tạm thời.",
        override val technicalDetail: String? = null
    ) : SourceError(message, technicalDetail)

    data class ExtractionBroken(
        override val message: String = "Cấu trúc trang nguồn đã thay đổi khiến bộ trích xuất thử nghiệm không đọc được dữ liệu.",
        override val technicalDetail: String? = null
    ) : SourceError(message, technicalDetail)

    data class PlaybackFailed(
        override val message: String = "Trình phát Media3 không thể giải mã hoặc tải luồng media này.",
        override val technicalDetail: String? = null
    ) : SourceError(message, technicalDetail)

    data class UnknownError(
        override val message: String = "Đã xảy ra lỗi không xác định khi tải nội dung.",
        override val technicalDetail: String? = null
    ) : SourceError(message, technicalDetail)
}

